/**
 * Regenerates src/lib/documents/logo-data.ts from the official logo asset.
 *
 * Customer documents (quotation, confirmation, receipt) are downloaded, printed
 * and saved as PDF away from the website, where /brand/logo.webp cannot be
 * fetched. The artwork is therefore embedded as a data: URI. Nothing here
 * creates or alters the logo — it only base64-encodes public/brand/logo.webp.
 *
 * Run after the logo asset changes:  npx tsx scripts/generate-document-logo.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const source = join(process.cwd(), 'public', 'brand', 'logo.webp')
const target = join(process.cwd(), 'src', 'lib', 'documents', 'logo-data.ts')
const base64 = readFileSync(source).toString('base64')

const body = `// GENERATED by scripts/generate-document-logo.ts from public/brand/logo.webp — do not edit by hand.
// Embedded so the logo renders in downloaded / printed / PDF documents with no network.

/** Natural size of the artwork (720 x 301), used to keep its aspect ratio. */
export const DOCUMENT_LOGO_WIDTH = 720
export const DOCUMENT_LOGO_HEIGHT = 301

export const DOCUMENT_LOGO_DATA_URI =
  'data:image/webp;base64,${base64}'
`
writeFileSync(target, body)
console.log(`Wrote ${target} (${base64.length} base64 chars)`)
